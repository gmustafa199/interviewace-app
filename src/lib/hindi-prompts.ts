export function hindiContextForRole(roleId: string): string | null {
  return HINDI_PROMPT_CONTEXTS[roleId] ?? null;
}

/**
 * Build the language-specific instructions block to append to any
 * interview prompt. For English this returns '' (no change needed);
 * for Hindi it returns the Hindi directive + role-specific context.
 */
export function languageInstructions(
  language: Language,
  roleId: string
): string {
  if (language !== 'hi') return '';
  const roleContext = hindiContextForRole(roleId) || '';
  return `${HINDI_INSTRUCTIONS}\n\n${roleContext}`;
}

